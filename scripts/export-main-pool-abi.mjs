// Regenerates shared/main-pool-abi.ts from ripe0x/shapes-fwa-pool's Foundry output. Run `forge build` there first:
//   SHAPES_FWA_POOL=../shapes-fwa-pool node scripts/export-main-pool-abi.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = process.env.SHAPES_FWA_POOL;
if (!root) throw new Error('Set SHAPES_FWA_POOL to the shapes-fwa-pool checkout');
const pick = (file, name = file) => JSON.parse(readFileSync(`${root}/out/${file}.sol/${name}.json`, 'utf8')).abi;
const entries = {
  packVaultAbi: pick('PackVault'),
  packManagerAbi: pick('PackManager'),
  packManagerFactoryAbi: pick('PackManagerFactory'),
  fwaV2Abi: pick('External', 'IFWAV2'),
};
const params = entries.packManagerFactoryAbi.find((entry) => entry.type === 'function' && entry.name === 'create')?.inputs.find((entry) => entry.type === 'tuple');
if (!params?.components.some((entry) => entry.name === 'gasSchedule')) throw new Error('Main build is stale: create Params has no named gasSchedule');
for (const abi of [entries.packVaultAbi, entries.packManagerAbi, entries.packManagerFactoryAbi]) {
  if (abi.some((entry) => ['keeperPolicy', 'policy', 'setPolicy'].includes(entry.name))) throw new Error('Main build still contains the retired external keeper policy');
}
for (const name of ['holderState', 'configurationHash', 'recover', 'recoverUnlist', 'recoverLiquidate', 'recoverCheckpoint', 'checkpointRefund', 'renewalQuote', 'relistEdgeFor', 'MAX_BUILD_BATCH', 'MAX_LIST_BATCH']) {
  if (!entries.packVaultAbi.some((entry) => entry.type === 'function' && entry.name === name)) throw new Error(`Main build is stale: missing ${name}`);
}
const valuesText = readFileSync(`${root}/deploy/manager.json`, 'utf8');
// Source text preserves uint128/uint64 values that JSON numbers otherwise round in JavaScript.
const values = JSON.parse(valuesText, (_key, value, context) => {
  if (typeof value !== 'number') return value;
  if (!context?.source) throw new Error('Node 22 or later is required to preserve exact deployment integers');
  return BigInt(context.source);
});
const aliases = { gasCeiling: 'gasCeilingWei', essentialCeiling: 'essentialCeilingWei', maxTip: 'maxTipWei', workFee: 'workFeeWei',
  routineCap: 'routineCapWei', routineRate: 'routineRatePerDayWei', essentialCap: 'essentialCapWei', essentialRate: 'essentialRatePerDayWei',
  reserve: 'reserveWei', tvlCap: 'tvlCapWei', acceptedMintFee: 'acceptedMintFeeWei', minDeposit: 'minDepositWei', minDistribution: 'minDistributionWei' };
const serialize = (components, source) => `{
${components.map((field) => {
  const value = source[aliases[field.name] ?? field.name];
  if (value === undefined) throw new Error(`Missing manager deployment value: ${field.name}`);
  if (field.type === 'tuple') return `  ${field.name}: ${serialize(field.components, value)},`;
  const width = field.type.startsWith('uint') ? Number(field.type.slice(4)) : undefined;
  if (!width || typeof value !== 'bigint' || value < 0n || value >= 1n << BigInt(width)) throw new Error(`Invalid manager deployment value: ${field.name}`);
  return `  ${field.name}: ${value}${width > 48 ? 'n' : ''},`;
}).join('\n')}
}`;
const defaultBody = `// Generated from shapes-fwa-pool deploy/manager.json; provisional local evaluation values, not production approval.
export const mainPoolDefaultsSha256 = '${createHash('sha256').update(valuesText).digest('hex')}';
export const defaultManagerParams = ${serialize(params.components, values)} as const;
`;
const body = ['// Generated by scripts/export-main-pool-abi.mjs from shapes-fwa-pool Foundry output. Do not edit.']
  .concat(Object.entries(entries).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)} as const;`))
  .join('\n');
const outputs = { 'shared/main-pool-abi.ts': body + '\n', 'shared/main-pool-defaults.ts': defaultBody };
for (const [file, expected] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== expected) throw new Error(`Stale main integration output: ${file}; regenerate from the reviewed main build`);
  } else writeFileSync(file, expected);
}
console.log(process.argv.includes('--check') ? 'main ABI and defaults match the reviewed build' : 'wrote shared/main-pool-abi.ts and shared/main-pool-defaults.ts');
