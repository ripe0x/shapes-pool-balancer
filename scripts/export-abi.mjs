// Regenerates shared/abi.ts from Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';
const pick = (file, name = file) => JSON.parse(readFileSync(`out/${file}.sol/${name}.json`, 'utf8')).abi;
const entries = {
  poolBalancerAbi: pick('PoolBalancer'),
  balancerFactoryAbi: pick('BalancerFactory'),
  fwaPoolAbi: pick('External', 'IFWAPool'),
  shapesAbi: pick('External', 'IShapes'),
  erc721Abi: pick('External', 'IERC721Min'),
};
const body = ['// Generated by scripts/export-abi.mjs from Foundry output. Do not edit.']
  .concat(Object.entries(entries).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)} as const;`))
  .join('\n');
writeFileSync('shared/abi.ts', body + '\n');
console.log('wrote shared/abi.ts');
