// Prize-mix planner. Prices, odds and the reserve use the same integer arithmetic as PoolBalancer and FWA
// StandardPool, so the numbers shown match the chain for the same curated set, markup, edge and mint fee.
import policyV1 from '../test/fixtures/keeper-policy-v1.json';
import enforcement from '../test/fixtures/keeper-enforcement.json';

export const BPS = 10_000n;
export const NUM = 10n ** 36n; // FWA INVERSE_WEIGHT_NUMERATOR
/** Initial calibration allocates Shape markup above the first 10%; runtime credit uses the stored rate. */
export const MIN_MARKUP_BPS = 1_000n;
export const MAX_BATCH = 5;
export const MAX_OPS = Number(enforcement.maxUnits);
export const MAX_SHAPES_PER_PLAN = 1_000;
/** Immutable V1 parameters exported by Solidity, for explicitly selected V1 simulations only. */
export const V1_POLICY = Object.fromEntries(Object.entries(policyV1).map(([k, v]) => [k, BigInt(v)])) as
  Record<keyof typeof policyV1, bigint>;
export const MAX_KEEPER_REWARD = V1_POLICY.maxReward;
export const rewardPrice = (baseFee: bigint) =>
  baseFee + V1_POLICY.priorityCap > V1_POLICY.maxGasPrice ? V1_POLICY.maxGasPrice : baseFee + V1_POLICY.priorityCap;
/** V1 surcharge preview. Arbitrary selected policies require their own bounded Balancer quotes. */
export const restockFeeAt = (baseFee: bigint) => V1_POLICY.restockGas * rewardPrice(baseFee) + V1_POLICY.restockFlat;

export interface KeeperWork {
  measuredGas: bigint;
  gasPrice: bigint;
  baseFee: bigint;
  reconciledDraws: bigint;
  listedShapeUnits: bigint;
  listedPrizes: bigint;
  processedDraws: bigint;
}
/** Exact V1 arithmetic for previews and simulations; arbitrary policies are consumed through absolute quotes. */
export function quoteV1(work: KeeperWork): bigint {
  const s = V1_POLICY;
  let price = rewardPrice(work.baseFee);
  if (work.gasPrice < price) price = work.gasPrice;
  const measured = work.measuredGas > s.maxGas ? s.maxGas : work.measuredGas;
  return (measured + s.overheadGas) * price
    + work.reconciledDraws * BigInt(policyV1.drawFee)
    + work.listedShapeUnits * BigInt(policyV1.shapeFee);
}

/** Generated by the Solidity enforcement fixture. Economic policies cannot change these bounds. */
export const KEEPER_LIMITS = Object.fromEntries(Object.entries(enforcement).map(([k, v]) => [k, BigInt(v)])) as
  Record<keyof typeof enforcement, bigint>;

type WorkCounts = Pick<KeeperWork, 'processedDraws' | 'reconciledDraws' | 'listedShapeUnits' | 'listedPrizes'>;
const lesser = (a: bigint, b: bigint) => a < b ? a : b;
export function immutableWorkGas(w: WorkCounts): bigint {
  const k = KEEPER_LIMITS;
  return lesser(k.maxGas, k.baseGas + k.processGas * w.processedDraws + k.reconcileGas * w.reconciledDraws
    + k.shapeGas * w.listedShapeUnits + k.prizeGas * w.listedPrizes);
}
/** Current-gas upper budget for validated work, independent of what a selected policy chooses to quote. */
export function immutableWorkBudget(w: WorkCounts, baseFee: bigint, maxReward: bigint): bigint {
  const k = KEEPER_LIMITS;
  const price = lesser(baseFee + k.priorityAllowance, k.gasPriceCeiling);
  return lesser(lesser(maxReward, k.hardMaxReward), (immutableWorkGas(w) + k.overheadGas) * price
    + k.workFee * (w.reconciledDraws + w.listedShapeUnits));
}
/** Payment ceiling for actual measured work and included bid; compensation itself remains the policy quote. */
export function paymentBound(w: KeeperWork, maxReward: bigint): bigint {
  const k = KEEPER_LIMITS;
  const price = lesser(w.gasPrice, lesser(w.baseFee + k.priorityAllowance, k.gasPriceCeiling));
  return lesser(lesser(maxReward, k.hardMaxReward), (lesser(w.measuredGas, immutableWorkGas(w)) + k.overheadGas) * price
    + k.workFee * (w.reconciledDraws + w.listedShapeUnits));
}
export interface ListingBatch { counts: Counts; units: number; prizes: number }
/** Same value order, Shape-unit limit and denomination limit as PoolInventory.fill. */
export function listingBatches(target: Counts, have: Counts): ListingBatch[] {
  const remaining = DENOMS.map((_, d) => Math.max(0, (target[d] ?? 0) - (have[d] ?? 0)));
  const batches: ListingBatch[] = [];
  while (remaining.some((n) => n > 0)) {
    const batch: ListingBatch = { counts: DENOMS.map(() => 0), units: 0, prizes: 0 };
    let sizes = 0;
    for (const d of BY_VALUE) {
      if (!remaining[d]) continue;
      if (sizes === Number(KEEPER_LIMITS.maxSizes)) break;
      const n = Math.min(remaining[d], Math.floor((MAX_OPS - batch.units) / SHAPES_IN[d]));
      if (!n) break;
      batch.counts[d] = n;
      batch.units += n * SHAPES_IN[d]; batch.prizes += n; remaining[d] -= n; sizes++;
      if (remaining[d]) break;
    }
    if (!batch.prizes) throw new Error('Invalid inventory batch limits');
    batches.push(batch);
  }
  return batches;
}
const workCounts = (processed: number, draws: number, units = 0, prizes = 0): WorkCounts => ({
  processedDraws: BigInt(processed), reconciledDraws: BigInt(draws), listedShapeUnits: BigInt(units), listedPrizes: BigInt(prizes),
});
export interface MaintenanceBudget {
  outstandingBudget: bigint; workingBuffer: bigint; total: bigint;
}
/** Only issued requests and one operating call; missing prizes never increase activation exposure. */
export function maintenanceBudgetAt(unreconciled: number, maxReward: bigint, baseFee: bigint, enabled = true): MaintenanceBudget {
  const outstandingBudget = BigInt(unreconciled) * immutableWorkBudget(workCounts(1, 1), baseFee, maxReward);
  const processing = immutableWorkBudget(workCounts(Number(KEEPER_LIMITS.maxProcessed), Number(KEEPER_LIMITS.maxReconciles)), baseFee, maxReward);
  const listing = immutableWorkBudget(workCounts(0, Number(KEEPER_LIMITS.maxReconciles), MAX_OPS, MAX_OPS), baseFee, maxReward);
  const workingBuffer = enabled ? (processing > listing ? processing : listing) : 0n;
  return { outstandingBudget, workingBuffer, total: outstandingBudget + workingBuffer };
}
/** Both budgets use one work/basefee/state snapshot. An increase requires the full candidate budget. */
export function policyActivationFundingAt(unreconciled: number, oldMaximum: bigint, candidateMaximum: bigint,
  baseFee: bigint, enabled: boolean, paidUpkeepEnabled: boolean, operatingCash: bigint) {
  const oldBudget = maintenanceBudgetAt(unreconciled, paidUpkeepEnabled ? oldMaximum : 0n, baseFee, enabled).total;
  const candidateBudget = maintenanceBudgetAt(unreconciled, candidateMaximum, baseFee, enabled).total;
  const required = candidateBudget;
  const shortfall = candidateBudget > oldBudget && required > operatingCash ? required - operatingCash : 0n;
  return { oldBudget, candidateBudget, required, shortfall, canActivate: shortfall === 0n };
}
export interface ReserveBreakdown extends MaintenanceBudget {
  inventoryCost: bigint; listingBudget: bigint;
}
/** Missing inventory and present work only. Unsold fees never offset liquid capital; closed pools hold actual draws. */
export function reserveBreakdownAt(target: Counts, have: Counts, mintFee: bigint, unreconciled: number,
  maxReward: bigint, baseFee: bigint, enabled = true): ReserveBreakdown {
  const maintenance = maintenanceBudgetAt(unreconciled, maxReward, baseFee, enabled);
  let inventoryCost = 0n, listingBudget = 0n;
  if (enabled) {
    target.forEach((n, d) => { if (n > (have[d] ?? 0)) inventoryCost += BigInt(n - (have[d] ?? 0)) * prizeCost(d, mintFee); });
    for (const batch of listingBatches(target, have)) {
      listingBudget += immutableWorkBudget(workCounts(0, 0, batch.units, batch.prizes), baseFee, maxReward);
    }
  }
  return { ...maintenance, inventoryCost, listingBudget, total: inventoryCost + listingBudget + maintenance.total };
}
export const requiredReserveAt = (target: Counts, have: Counts, mintFee: bigint, unreconciled: number,
  maxReward: bigint, baseFee: bigint, enabled = true): bigint =>
  reserveBreakdownAt(target, have, mintFee, unreconciled, maxReward, baseFee, enabled).total;

const E = 10n ** 18n;
/**
 * Prize sizes (wei), PoolBalancer's size table: 0-8 the mainnet Shapes ladder (each prize one Shape), 9-15 Draw Packs
 * holding the fewest Shapes that sum to the value. Not in value order; use BY_VALUE for that.
 */
export const DENOMS: readonly bigint[] = [
  E / 100n, E / 20n, E / 10n, E / 2n, E, 5n * E, 10n * E, 50n * E, 100n * E,
  E / 50n, (3n * E) / 100n, E / 5n, E / 4n, 2n * E, (5n * E) / 2n, 25n * E,
];
export const DENOM_LABELS = ['0.01', '0.05', '0.1', '0.5', '1', '5', '10', '50', '100', '0.02', '0.03', '0.2', '0.25', '2', '2.5', '25'];
/** Sizes that are single Shapes (the rest are packs). */
export const SHAPE_SIZES = 9;
export const isPack = (d: number) => d >= SHAPE_SIZES;
/** Shapes inside one prize of each size; each pays the Shapes mint fee (PoolBalancer.SHAPES_IN). */
export const SHAPES_IN: readonly number[] = [1, 1, 1, 1, 1, 1, 1, 1, 1, 2, 3, 2, 3, 2, 3, 3];
/** The most Shapes any prize holds; the worst-batch reserve charges each prize this many mint fees. */
export const MAX_SHAPES_IN = 3;
/** Size indices smallest value first. */
export const BY_VALUE: readonly number[] = DENOMS.map((_, i) => i).sort((a, b) => (DENOMS[a] < DENOMS[b] ? -1 : 1));
/** ETH to create one prize of size d: its backing plus a mint fee per Shape inside. */
export const prizeCost = (d: number, mintFee: bigint) => DENOMS[d] + BigInt(SHAPES_IN[d]) * mintFee;
export const prizeLabel = (d: number) => `${DENOM_LABELS[d]} ETH ${isPack(d) ? 'Pack' : 'Shape'}`;

export type Counts = number[]; // length 16, indexed like DENOMS

export interface PoolInputs {
  curatedBases: bigint[]; // creator-assigned values (wei): an unlisted NFT's FWA price (curated NFTs carry no markup)
  markupBps: number;
  /** Stored payout percentage. Omit only for a new design, to preview its initial suggestion. */
  creatorRevenueBps?: number;
  edgeBps: number; // FWA factory edgeBps (500 at time of review)
  mintFee: bigint; // Shapes.mintFee()
  restockFee: bigint; // PoolBalancer.restockFee(), per Shape (restockFeeAt(basefee))
  /** FWA prices of curated NFTs already listed, matching the first entries of `curatedBases`; entries without a price
   *  are new and priced at their value. */
  curatedPrices?: bigint[];
  /** FWA prices of Shape prizes already listed, by size index (0..15): each size's array holds the actual listed price
   *  of each active prize of that size, which keeps the markup and fees in force when it was listed. Prizes beyond the
   *  listed count (new ones the plan adds) are priced at the current markup and fees. Parallels `curatedPrices`. */
  shapePrices?: bigint[][];
  /** Cached immutable-enforced maximum read from the selected pool/policy. */
  policyMaxReward?: bigint;
  /** Exact surcharge per new prize, indexed by denomination. Supports pack-specific future policies. */
  restockFees?: readonly bigint[];
  /** On-chain quotes for representative work. The workload assumptions are exported below. */
  keeperQuotes?: { replace: readonly bigint[]; reconcile: bigint; setup?: bigint };
  /** Current block basefee used by the policy-independent reserve calculations. */
  baseFee: bigint;
  gasPrice?: bigint;
  /** Explicit local V1 preview. Other policies require their actual absolute quotes. */
  v1Preview?: boolean;
  unreconciled?: number;
  enabled?: boolean;
  paidUpkeepEnabled?: boolean;
}

/** A missing selected-policy maximum must not silently adopt V1's economics. */
export function effectivePolicyMaximum(inputs: Pick<PoolInputs, 'paidUpkeepEnabled' | 'policyMaxReward' | 'v1Preview'>): bigint {
  if (inputs.paidUpkeepEnabled === false) return 0n;
  if (inputs.policyMaxReward !== undefined) return inputs.policyMaxReward;
  if (inputs.v1Preview === true) return MAX_KEEPER_REWARD;
  throw new Error('Policy maximum unavailable');
}

export function packPlan(counts: Counts): bigint {
  let p = 0n;
  counts.forEach((c, d) => {
    if (c < 0 || c > 0xffff || !Number.isInteger(c)) throw new Error('bad count');
    p |= BigInt(c) << BigInt(16 * d);
  });
  return p;
}

export function unpackPlan(p: bigint): Counts {
  // Plans saved before pack sizes existed decode the same: their high counts are zero.
  return DENOMS.map((_, d) => Number((p >> BigInt(16 * d)) & 0xffffn));
}

/** A prize's listed price less its restocking fees (PoolBalancer._prizeBase): cost plus the markup on its backing. */
export const prizeBase = (d: number, mintFee: bigint, markupBps: number) => prizeCost(d, mintFee) + (DENOMS[d] * BigInt(markupBps)) / BPS;
/** A prize's FWA listing price (PoolBalancer._fillDeficit). */
export const prizeRestockFee = (d: number, i: Pick<PoolInputs, 'restockFee' | 'restockFees'>) =>
  i.restockFees?.[d] ?? BigInt(SHAPES_IN[d]) * i.restockFee;
export const prizePrice = (d: number, i: Pick<PoolInputs, 'mintFee' | 'markupBps' | 'restockFee' | 'restockFees'>) =>
  prizeBase(d, i.mintFee, i.markupBps) + prizeRestockFee(d, i);
export const weightOf = (price: bigint) => NUM / price;

/** A curated NFT's FWA price: its live listing price if listed, else its value. */
export const curatedPrice = (i: number, inputs: Pick<PoolInputs, 'curatedBases' | 'curatedPrices'>) =>
  inputs.curatedPrices?.[i] ?? inputs.curatedBases[i];

export function curatedTotals(inputs: Pick<PoolInputs, 'curatedBases' | 'curatedPrices'>) {
  let w = 0n;
  let wp = 0n;
  for (let i = 0; i < inputs.curatedBases.length; i++) {
    const p = curatedPrice(i, inputs);
    const wi = weightOf(p);
    w += wi;
    wp += wi * p;
  }
  return { w, wp };
}

/** The FWA price of the k-th listed prize of size `d`: the price it was listed at if it is already listed, else the
 *  price a new prize of that size takes at the current markup and fees. */
export const shapePriceAt = (d: number, k: number, inputs: Pick<PoolInputs, 'mintFee' | 'markupBps' | 'restockFee' | 'restockFees' | 'shapePrices'>) =>
  inputs.shapePrices?.[d]?.[k] ?? prizePrice(d, inputs);

export function shapeTotals(counts: Counts, inputs: PoolInputs) {
  let w = 0n;
  let wp = 0n;
  counts.forEach((n, d) => {
    for (let k = 0; k < n; k++) {
      const p = shapePriceAt(d, k, inputs);
      const wi = weightOf(p);
      w += wi;
      wp += wi * p;
    }
  });
  return { w, wp };
}

/** Unsettled draws a fully stocked board still admits a purchase with (PoolBalancer's fill gate counts each
 *  unreconciled draw as the loss of a 0.01 ETH prize's weight, 1e36 / backing, and admits while 70% of the target's
 *  weight remains), capped at FWA's MAX_BATCH. Below MAX_BATCH the board pauses while that many draws are unsettled. */
export function pendingDrawsAdmitted(counts: Counts): number {
  const w = counts.reduce((s, n, d) => s + BigInt(n) * (NUM / DENOMS[d]), 0n);
  const k = Number((3_000n * w) / (BPS * (NUM / DENOMS[0])));
  return Math.min(k, MAX_BATCH);
}

export const capitalOf = (counts: Counts) => counts.reduce((s, n, d) => s + BigInt(n) * DENOMS[d], 0n);
export const shapeCount = (counts: Counts) => counts.reduce((s, n) => s + n, 0);

export interface Tier {
  label: string;
  kind: 'curated' | 'shape'; // 'shape': a Shape or Pack prize of size `size`
  size?: number;
  count: number;
  value: bigint; // what a winner receives: the creator's value, or the ETH a Shape or pack redeems for
  listPrice: bigint;
  oddsPpm: number; // combined probability of this tier per draw, parts per million
}

export interface Evaluation {
  feasible: boolean;
  reasons: string[];
  drawPrice: bigint; // FWA acquisitionFee
  curatedOddsBps: number; // floor, as checked on chain
  curatedOddsPpm: number;
  tiers: Tier[];
  capital: bigint;
  shapes: number;
  requiredReserve: bigint; // PoolBalancer.requiredReserve() with the target fully listed and reconciled
  ownerProceedsPerDraw: bigint; // EV paid to the owner on each delivered draw
}

export function evaluate(counts: Counts, inputs: PoolInputs): Evaluation {
  const c = curatedTotals(inputs);
  const s = shapeTotals(counts, inputs);
  const tW = c.w + s.w;
  const reasons: string[] = [];
  const capital = capitalOf(counts);
  const shapes = shapeCount(counts);
  const ev = tW === 0n ? 0n : (c.wp + s.wp) / tW;
  const drawPrice = (ev * (BPS + BigInt(inputs.edgeBps))) / BPS;
  const curatedOddsBps = tW === 0n ? 0 : Number((c.w * BPS) / tW);
  const curatedOddsPpm = tW === 0n ? 0 : Number((c.w * 1_000_000n) / tW);

  if (shapes === 0) reasons.push('Plan has no Shapes');
  if (shapes > MAX_SHAPES_PER_PLAN) reasons.push(`More than ${MAX_SHAPES_PER_PLAN} Shapes`);

  const tiers: Tier[] = [];
  inputs.curatedBases.forEach((b, i) => {
    const p = curatedPrice(i, inputs);
    tiers.push({ label: `Curated #${i + 1}`, kind: 'curated', count: 1, value: b, listPrice: p, oddsPpm: Number((weightOf(p) * 1_000_000n) / (tW || 1n)) });
  });
  counts.forEach((n, d) => {
    if (!n) return;
    // Each listed prize of this size keeps its own price (different markup/fees at listing time), so weigh them one by
    // one; new prizes the plan adds beyond the listed count fall back to the current price.
    let dw = 0n;
    for (let k = 0; k < n; k++) dw += weightOf(shapePriceAt(d, k, inputs));
    tiers.push({ label: prizeLabel(d), kind: 'shape', size: d, count: n, value: DENOMS[d], listPrice: shapePriceAt(d, 0, inputs), oddsPpm: Number((dw * 1_000_000n) / (tW || 1n)) });
  });

  return {
    feasible: reasons.length === 0,
    reasons,
    drawPrice,
    curatedOddsBps,
    curatedOddsPpm,
    tiers,
    capital,
    shapes,
    requiredReserve: requiredReserveAt(counts, counts, inputs.mintFee, inputs.unreconciled ?? 0,
      effectivePolicyMaximum(inputs), inputs.baseFee),
    ownerProceedsPerDraw: ev,
  };
}

const toEth = (x: bigint) => Number(x) / 1e18;

/** Historical measured-span estimates, not policy parameters or receipt measurements of this candidate.
 *  A replacement quote includes one reconcile plus mint/list; larger packs use their own operation estimate. */
export const RECONCILE_GAS_ESTIMATE = 137_000n;
export const REPLACEMENT_GAS_ESTIMATE = DENOMS.map((_, d) =>
  d < SHAPE_SIZES ? 864_000n : SHAPES_IN[d] === 2 ? 1_000_000n : 1_100_000n);
export function keeperWorkAt(baseFee: bigint, gasPrice: bigint, d?: number): KeeperWork {
  return {
    measuredGas: d === undefined ? RECONCILE_GAS_ESTIMATE : REPLACEMENT_GAS_ESTIMATE[d],
    gasPrice, baseFee, reconciledDraws: 1n,
    listedShapeUnits: d === undefined ? 0n : BigInt(SHAPES_IN[d]),
    listedPrizes: d === undefined ? 0n : 1n,
    processedDraws: 0n,
  };
}

/** Expected Shape allocation above 10% divided by actual FWA owner proceeds, rounded down to basis points.
 * FWA escrows floor(weighted EV) plus its edge, but credits the owner only floor(weighted EV); VRF is separate. */
export function suggestedCreatorRevenueBps(counts: Counts, inputs: PoolInputs): number {
  const c = curatedTotals(inputs);
  const s = shapeTotals(counts, inputs);
  const totalWeight = c.w + s.w;
  if (totalWeight === 0n) return 0;
  const ownerProceeds = (c.wp + s.wp) / totalWeight;
  if (ownerProceeds === 0n) return 0;
  const allocationBps = BigInt(inputs.markupBps) > MIN_MARKUP_BPS ? BigInt(inputs.markupBps) - MIN_MARKUP_BPS : 0n;
  let weightedAllocation = 0n;
  counts.forEach((n, d) => {
    const allocation = DENOMS[d] * allocationBps / BPS;
    for (let k = 0; k < n; k++) weightedAllocation += weightOf(shapePriceAt(d, k, inputs)) * allocation;
  });
  return Number(weightedAllocation * BPS / (totalWeight * ownerProceeds));
}

/** Per-draw expectation at actual listed prices. Collections round credit once per collected amount. */
export function economics(counts: Counts, inputs: PoolInputs) {
  const ev = evaluate(counts, inputs);
  const creatorRevenueBps = inputs.creatorRevenueBps ?? suggestedCreatorRevenueBps(counts, inputs);
  if (!Number.isInteger(creatorRevenueBps) || creatorRevenueBps < 0 || creatorRevenueBps > 10_000) {
    throw new Error('Creator revenue share must be 0 to 10000 basis points');
  }
  const totalWeight = curatedTotals(inputs).w + shapeTotals(counts, inputs).w;
  const price = inputs.gasPrice ?? rewardPrice(inputs.baseFee);
  const keeperCostKnown = inputs.paidUpkeepEnabled === false || (inputs.keeperQuotes !== undefined
    ? counts.every((n, d) => !n || inputs.keeperQuotes!.replace[d] !== undefined)
    : inputs.v1Preview === true);
  const quoted = (d?: number) => {
    if (inputs.paidUpkeepEnabled === false) return 0n;
    if (inputs.keeperQuotes) return d === undefined ? inputs.keeperQuotes.reconcile : inputs.keeperQuotes.replace[d];
    if (!inputs.v1Preview) return undefined;
    const work = keeperWorkAt(inputs.baseFee, price, d);
    return lesser(quoteV1(work), paymentBound(work, effectivePolicyMaximum(inputs)));
  };
  let backingWeighted = 0n, mintWeighted = 0n, surchargeWeighted = 0n, keeperWeighted = 0n;
  for (let i = 0; i < inputs.curatedBases.length; i++) {
    keeperWeighted += weightOf(curatedPrice(i, inputs)) * (quoted() ?? 0n);
  }
  counts.forEach((n, d) => {
    for (let k = 0; k < n; k++) {
      const weight = weightOf(shapePriceAt(d, k, inputs));
      backingWeighted += weight * DENOMS[d];
      mintWeighted += weight * BigInt(SHAPES_IN[d]) * inputs.mintFee;
      surchargeWeighted += weight * prizeRestockFee(d, inputs);
      keeperWeighted += weight * (quoted(d) ?? 0n);
    }
  });
  const average = (weighted: bigint) => totalWeight === 0n ? 0n : weighted / totalWeight;
  const creator = ev.ownerProceedsPerDraw * BigInt(creatorRevenueBps) / BPS;
  const retained = ev.ownerProceedsPerDraw - creator;
  const replacement = average(backingWeighted);
  const mint = average(mintWeighted);
  const keeper = keeperCostKnown ? average(keeperWeighted) : undefined;
  return {
    creatorRevenueBps,
    keeperCostKnown,
    ownerProceeds: toEth(ev.ownerProceedsPerDraw),
    creatorEarningsPerDraw: toEth(creator),
    retainedRevenuePerDraw: toEth(retained),
    replacementCostsPerDraw: toEth(replacement),
    mintFeesPerDraw: toEth(mint),
    /** Current surcharge expectation, not evidence of surcharge revenue actually collected. */
    restockFeesPerDraw: toEth(average(surchargeWeighted)),
    /** Estimates assume one maintenance call per won prize; complete execution simulation decides keeper bids. */
    keeperPayPerDraw: keeper === undefined ? undefined : toEth(keeper),
    marginPerDraw: keeper === undefined ? undefined : toEth(retained - replacement - mint - keeper),
  };
}
